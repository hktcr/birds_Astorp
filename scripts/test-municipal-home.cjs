'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const root=path.resolve(__dirname,'..');
const prefix=fs.existsSync(path.join(root,'static/js/municipal-home.js'))?'static/':'';
const home=require(path.join(root,prefix+'js/municipal-home.js'));
const live=require(path.join(root,prefix+'js/municipal-home-live.js'));
const data=require(path.join(root,prefix+'js/municipal-preview-data.js'));
const fixture=JSON.parse(fs.readFileSync(path.join(root,prefix+'data/municipal-preview.json'),'utf8'));
const checked=data.verify(fixture);
const year=Number(checked.source.toDay.slice(0,4));
const model=home.model(checked,year);
assert.equal(model.count,checked.source.aggregateManifest.find(x=>x.year===year).species);
assert.equal(home.model({...checked,records:[...checked.records,...checked.records]},year).count,model.count);
assert.equal(home.model({...checked,records:checked.records.filter(x=>!x.day.startsWith(year+'-'))},year).count,0);
assert.throws(()=>data.verify({...fixture,source:{...fixture.source,complete:false}}));
assert.equal(home.dateLabel('2026-01-01'),'1 januari');
assert.equal(live.stockholmDay('2026-01-01T00:00:00+01:00'),'2026-01-01');
assert.equal(live.stockholmDay('2025-12-31T23:00:00Z'),'2026-01-01');
assert.equal(live.stockholmDay('2026-06-30T22:00:00Z'),'2026-07-01');
assert.equal(live.stockholmDay('2026-01-01T00:00:00-05:00'),'2026-01-01');
assert.throws(()=>live.stockholmDay('2026-01-01T00:00:00'));
assert.equal(home.current({...checked,source:{...checked.source,mode:'snapshot',retrievedAt:'2026-10-29T18:22:11Z'}},new Date('2026-11-20T06:30:00Z'),live),false);
const fresh={source:{mode:'live',retrievedAt:'2026-11-20T06:30:00Z',toDay:'2026-11-20'}};
assert.equal(home.current(fresh,new Date('2026-11-20T06:40:00Z'),live),true);
assert.equal(home.current(fresh,new Date('2026-11-20T06:46:00Z'),live),false);
assert.equal(home.current(fresh,new Date('2026-11-20T06:29:00Z'),live),false);
assert.equal(home.current(fresh,new Date('2026-11-21T06:40:00Z'),live),false);
console.log('municipal homepage: data, freshness and timezone checks passed');
